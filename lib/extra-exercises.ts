import type { ExerciseDefinition } from "./exercises";

function pattern(
  label: string,
  description: string,
  category: string,
  focus: string,
  notes: number[],
  starts?: number[],
  durations?: number[],
): ExerciseDefinition {
  const icons: Record<string, string> = {
    Basics: "◎",
    Scales: "⋰",
    Intervals: "↗",
    Arpeggios: "♬",
    Phrases: "♫",
    Timing: "◷",
  };
  return {
    name: label,
    label,
    description,
    category,
    focus,
    icon: icons[category],
    pattern: notes,
    starts,
    durations,
  };
}

